// Подключаем необходимые библиотеки
#include <iostream>            // Для ввода-вывода (std::cout)
#include <thread>              // Для работы с потоками (std::thread)
#include <vector>              // Для работы с динамическими массивами (std::vector)
#include <queue>               // Для работы с очередью (std::queue)
#include <future>              // Для получения результатов асинхронных операций (std::future)
#include <functional>          // Для работы с функциями как объектами (std::function)
#include <mutex>               // Для работы с мьютексами (std::mutex)
#include <condition_variable>  // Для синхронизации потоков (std::condition_variable)

// Класс ThreadPool (Пул потоков) - позволяет переиспользовать потоки для разных задач
// Вместо создания нового потока для каждой задачи, создаём фиксированное количество потоков,
// которые берут задачи из общей очереди и выполняют их
class ThreadPool {
private:
    std::vector<std::thread> workers;           // Вектор рабочих потоков (worker threads)
    std::queue<std::function<void()>> tasks;    // Очередь задач для выполнения (каждая задача - функция void())
    std::mutex queue_mutex;                     // Мьютекс для защиты доступа к очереди задач
    std::condition_variable condition;          // Условная переменная для оповещения потоков о новых задачах
    bool stop = false;                          // Флаг завершения работы пула (false = работает)

public:
    // Конструктор: создаёт пул потоков с заданным количеством рабочих потоков
    // num_threads - количество потоков в пуле (обычно равно количеству ядер процессора)
    ThreadPool(size_t num_threads) {
        // Создаём num_threads рабочих потоков
        for (size_t i = 0; i < num_threads; ++i) {
            // emplace_back создаёт поток прямо в векторе (избегая копирования)
            // Каждый поток выполняет лямбда-функцию [this]() {...}
            // [this] - захват this (указателя на текущий объект ThreadPool) для доступа к полям класса
            workers.emplace_back([this]() {
                // Бесконечный цикл работы потока (выполняется, пока поток не будет остановлен)
                while (true) {
                    std::function<void()> task;  // Переменная для хранения текущей задачи

                    // Блок для работы с очередью (критическая секция)
                    {
                        // Захватываем мьютекс с возможностью временного освобождения (unique_lock, а не lock_guard)
                        // unique_lock нужен для condition.wait (который может временно освобождать мьютекс)
                        std::unique_lock<std::mutex> lock(this->queue_mutex);

                        // Ожидаем, пока не появится задача или не будет установлен флаг завершения
                        // wait принимает два параметра: lock и предикат (лямбда-функция)
                        // Поток засыпает и освобождает мьютекс, пока предикат возвращает false
                        // Когда приходит notify_one/notify_all, поток просыпается и проверяет предикат
                        this->condition.wait(lock, [this](){
                            // Выходим из ожидания, если stop=true или в очереди есть задачи
                            return this->stop || !this->tasks.empty();
                        });

                        // Если флаг остановки установлен и очередь пуста, завершаем работу потока
                        if (this->stop && this->tasks.empty()) {
                            return;  // Выходим из лямбда-функции (поток завершается)
                        }

                        // Извлекаем задачу из очереди
                        task = std::move(this->tasks.front());  // Берём первую задачу (std::move для оптимизации)
                        this->tasks.pop();                      // Удаляем её из очереди
                    }  // Мьютекс автоматически освобождается при выходе из блока

                    // Выполняем задачу (вне критической секции, чтобы другие потоки могли работать с очередью)
                    task();  // Вызываем функцию task (это функция типа void())
                }
            });
        }
    }

    // Шаблонный метод для добавления задачи в пул
    // F - тип функции (может быть функцией, лямбдой, функтором)
    // Args... - переменное количество типов аргументов (variadic template)
    // decltype(f(args...)) - определяет тип возвращаемого значения функции f с аргументами args
    template<class F, class... Args>
    auto submit(F&& f, Args&&... args) -> std::future<decltype(f(args...))> {
        // Определяем тип возвращаемого значения функции
        // decltype выводит тип выражения f(args...) на этапе компиляции
        using return_type = decltype(f(args...));

        // Создаём упакованную задачу (packaged_task) - обёртка для функции с возможностью получения результата через future
        // std::bind связывает функцию f с аргументами args..., создавая callable объект без параметров
        // std::forward<F>(f) - perfect forwarding (сохраняет тип f: lvalue или rvalue)
        // std::forward<Args>(args)... - perfect forwarding для каждого аргумента
        // make_shared создаёт shared_ptr (умный указатель с подсчётом ссылок)
        auto task = std::make_shared<std::packaged_task<return_type()>>(
            std::bind(std::forward<F>(f), std::forward<Args>(args)...)
        );

        // Получаем future для получения результата выполнения задачи
        // future - объект, который содержит результат асинхронной операции (или будет содержать в будущем)
        std::future<return_type> res = task->get_future();

        // Добавляем задачу в очередь (критическая секция)
        {
            // Захватываем мьютекс для безопасного доступа к очереди
            // lock_guard автоматически освобождает мьютекс при выходе из блока
            std::lock_guard<std::mutex> lock(queue_mutex);

            // Проверяем, что пул не остановлен (иначе нельзя добавлять задачи)
            if (stop) {
                throw std::runtime_error("submit on stopped ThreadPool");
            }

            // Добавляем задачу в очередь как лямбда-функцию, которая выполнит упакованную задачу
            // emplace создаёт элемент прямо в очереди (избегая копирования)
            // [task] - захват shared_ptr по значению (увеличивает счётчик ссылок, task не будет удалён)
            // (*task)() - разыменовываем shared_ptr и вызываем оператор () у packaged_task
            tasks.emplace([task](){ (*task)(); });
        }  // Мьютекс освобождается

        // Оповещаем один ожидающий поток о том, что появилась новая задача
        // Один из потоков проснётся и извлечёт задачу из очереди
        condition.notify_one();

        // Возвращаем future, через который можно будет получить результат выполнения функции
        return res;
    }

    // Деструктор: корректно завершает работу пула потоков
    ~ThreadPool() {
        // Блок для установки флага завершения
        {
            // Захватываем мьютекс для безопасной установки флага
            std::lock_guard<std::mutex> lock(queue_mutex);
            stop = true;  // Устанавливаем флаг завершения работы (потоки должны завершиться)
        }  // Мьютекс освобождается

        // Оповещаем все ожидающие потоки о завершении работы
        // Все потоки проснутся, увидят stop=true и завершатся
        condition.notify_all();

        // Ожидаем завершения всех рабочих потоков
        for (std::thread &worker : workers) {
            // Проверяем, можно ли присоединить поток (он не был присоединён ранее)
            if (worker.joinable()) {
                worker.join();  // Блокирует выполнение, пока поток не завершится
            }
        }
    }
};

// Функция для вычисления факториала числа
// n - число, для которого вычисляется факториал
// Возвращает n! = 1 * 2 * 3 * ... * n
// unsigned long long используется для больших чисел (до 20!)
unsigned long long factorial(int n) {
    // Проверяем, что n не отрицательное (факториал определён только для неотрицательных чисел)
    if (n < 0) {
        // Бросаем исключение, если n < 0
        throw std::invalid_argument("n must be non-negative");
    }

    unsigned long long result = 1;  // Начальное значение факториала (0! = 1, 1! = 1)

    // Умножаем все числа от 2 до n
    for (int i = 2; i <= n; ++i) {
        // Приводим i к unsigned long long для избежания переполнения
        result *= static_cast<unsigned long long>(i);
    }

    return result;  // Возвращаем результат
}

// Главная функция программы
int main() {
    // Константа: количество рабочих потоков в пуле
    const size_t num_threads = 4;

    // Создаём пул потоков с 4 рабочими потоками
    ThreadPool pool(num_threads);

    // Вектор чисел, для которых будем вычислять факториалы
    std::vector<int> numbers = {5, 7, 10, 12, 15, 20};

    // Вектор для хранения future-объектов (результатов асинхронных операций)
    std::vector<std::future<unsigned long long>> futures;

    // Резервируем память для future-объектов (оптимизация, избегаем перевыделения)
    futures.reserve(numbers.size());

    // Отправляем задачи на вычисление факториалов в пул потоков
    for (int n : numbers) {
        // Отправляем задачу в пул: вызов функции factorial с аргументом n
        // submit возвращает future<unsigned long long>, который мы сохраняем в вектор
        // Потоки из пула будут параллельно выполнять эти задачи
        futures.push_back(pool.submit(factorial, n));
    }

    // Получаем результаты из future-объектов и выводим их
    for (size_t i = 0; i < numbers.size(); ++i) {
        try {
            // get() блокирует выполнение до тех пор, пока задача не завершится
            // и возвращает результат вычисления (значение, которое вернула функция factorial)
            unsigned long long result = futures[i].get();

            // Выводим результат (число и его факториал)
            std::cout << "Факториал(" << numbers[i] << ") = " << result << std::endl;
        } catch (const std::exception& e) {
            // Ловим исключения, которые могли возникнуть при вычислении (например, n < 0)
            // e.what() возвращает текст сообщения об ошибке
            std::cerr << "Ошибка при вычислении факториала: " << e.what() << std::endl;
        }
    }

    // По завершении main() автоматически вызывается деструктор ThreadPool
    // Это корректно завершает все потоки (устанавливает stop=true, notify_all, join)
    return 0;
}
