#ifndef DATE_H
#define DATE_H

#include <string> // Для использования std::string

// Структура для хранения даты (день, месяц, год)
struct Date {
    int day;    // День (1-31)
    int month;  // Месяц (1-12)
    int year;   // Год (например, 2024)

    // Конструктор по умолчанию (создает дату 1.1.2000)
    Date();

    // Конструктор с параметрами (создает дату с указанными значениями)
    Date(int d, int m, int y);

    // Метод для преобразования даты в строку формата "день.месяц.год"
    std::string toString() const;
};

#endif 